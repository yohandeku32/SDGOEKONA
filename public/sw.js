const CACHE_PREFIX = 'sdgoekona-pwa-';
const CACHE_NAME = CACHE_PREFIX + 'v1';

const APP_SHELL = [
  './',
  './manifest.webmanifest',
  './pwa-icon.svg',
  './logo-kabupaten-kupang.png',
  './logo-tut-wuri.png'
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then((cache) => cache.addAll(APP_SHELL))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((key) => key.startsWith(CACHE_PREFIX) && key !== CACHE_NAME)
            .map((key) => caches.delete(key))
        )
      )
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;

  if (request.method !== 'GET') {
    return;
  }

  const url = new URL(request.url);

  if (url.origin !== self.location.origin) {
    return;
  }

  // Jangan pernah cache API karena data absensi harus selalu terbaru.
  if (url.pathname.startsWith('/api/')) {
    return;
  }

  // HTML selalu mencoba jaringan dulu agar deploy terbaru langsung dipakai.
  if (request.destination === 'document') {
    event.respondWith(
      fetch(request)
        .then((response) => {
          const copy = response.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put(request, copy));
          return response;
        })
        .catch(() =>
          caches.match(request).then((cached) => cached || caches.match('./'))
        )
    );
    return;
  }

  // Asset statis: gunakan cache lebih dahulu, lalu ambil dari jaringan.
  event.respondWith(
    caches.match(request).then((cached) => {
      if (cached) {
        return cached;
      }

      return fetch(request).then((response) => {
        if (response.ok && response.type === 'basic') {
          const copy = response.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put(request, copy));
        }

        return response;
      });
    })
  );
});
